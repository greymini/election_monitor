def log(message: str) -> None:
    print(f"[dev_stack] {message}", flush=True)


def fail(message: str) -> None:
    print(f"[dev_stack] ERROR {message}", file=sys.stderr, flush=True)
    raise SystemExit(1)


def read_state() -> dict:
    if STATE_FILE.exists():
        try:
            return json.loads(STATE_FILE.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            log("state.json is unreadable; treating the stack as unbuilt")
    return {"done": [], "version": 1}


def write_state(state: dict) -> None:
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    STATE_FILE.write_text(json.dumps(state, indent=2), encoding="utf-8")


def run(args: list[str], what: str, env: dict | None = None) -> None:
    """Run a loader as a subprocess and fail loudly.

    Subprocesses rather than in-process calls on purpose: these are the exact
    commands RUN.md tells an operator to type, argument parsing included. An
    in-process call would let this script drift into being a second, friendlier
    pipeline that works where the documented one does not.
    """
    log(f"$ {' '.join(str(a) for a in args[1:])}")
    proc = subprocess.run(
        [str(a) for a in args], cwd=APP_ROOT,
        env={**os.environ, **(env or {})},
        capture_output=True, text=True, encoding="utf-8", errors="replace",
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout or "")
        sys.stderr.write(proc.stderr or "")
        fail(f"{what} failed with exit code {proc.returncode}")
    for line in (proc.stderr or "").splitlines():
        if any(tag in line for tag in (" WARNING ", " ERROR ")) or "loaded" in line:
            print(f"    {line}", flush=True)


def _printed_password(stdout: str, phone: str) -> str:
    """Read back the password `create_admin --generate-password` printed.

    Parsing another script's stdout is not lovely. The alternative is to hash a
    password here and insert the row directly, which would mean this stack's
    users were created by a path no operator ever uses - and the login flow is
    one of the things the stack exists to exercise.
    """
    marker = f"Password for {phone}: "
    for line in (stdout or "").splitlines():
        if marker in line:
            return line.split(marker, 1)[1].strip()
    fail(f"scripts.create_admin printed no password for {phone}. Its output was:\n{stdout}")
    raise AssertionError("unreachable")


