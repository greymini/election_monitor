def step_migrate(py: str) -> None:
    run([py, "-m", "db.apply_migrations"], "db.apply_migrations")
    report_capabilities()


def report_capabilities() -> None:
    """Say out loud which extensions this cluster has (N4).

    `vector` is required by 0001; PostGIS, pg_trgm and unaccent are not used by
    this schema (booth location is lon/lat doubles, D-006), so they are only
    reported, never needed.
    """
    import psycopg

    with psycopg.connect(os.environ["DATABASE_URL"], row_factory=psycopg.rows.dict_row) as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT extname, extversion FROM pg_extension ORDER BY extname")
            rows = cur.fetchall()
    log("extensions: " + ", ".join(f"{r['extname']} {r['extversion']}" for r in rows))


def step_seed(py: str) -> None:
    run([py, "-m", "db.seed.load_seed"], "db.seed.load_seed")


def step_generate(py: str, args) -> None:
    run([py, "-m", "ingest.mock_documents", "--ac", str(args.ac),
         "--out-dir", str(MOCK_DIR), "--booths", str(args.booths),
         "--roll-booths", str(args.roll_booths), "--seed", str(args.seed)],
        "ingest.mock_documents")


def manifest() -> dict:
    path = MOCK_DIR / "manifest.json"
    if not path.exists():
        fail(f"{path} is missing. Re-run with --rebuild.")
    return json.loads(path.read_text(encoding="utf-8"))


def docs_of(kind: str) -> list[dict]:
    return [d for d in manifest()["documents"] if d["kind"] == kind]


def step_ps_list(py: str) -> None:
    """Every PS list, per block.

    One file per block because `parse_pslist` takes a single `--block` for the
    panchayats it has to create, and a panchayat filed under the wrong block
    corrupts every block rollup silently. A real CEO list is published per AC
    with a block column; reading that column is work the parser does not do yet,
    and inventing it here would hide the gap.
    """
    for d in docs_of("ps_list"):
        cmd = [py, "-m", "ingest.parse_pslist", str(MOCK_DIR / d["path"]),
               "--ac", str(d["ac"]), "--election", d["election"], "--load",
               "--block", str(d["block_id"])]
        if d["anchor"]:
            cmd.append("--anchor")
        run(cmd, f"parse_pslist {d['path']}")


def step_form20(py: str) -> None:
    """Every Form 20: parse, resolve the columns, validate, then load.

    No `--skip-ac-check` anywhere. The gate that compares each column's booth
    sum against the published AC total at tolerance zero is the one the README
    calls the reason to trust a number, and a dev stack that disabled it would
    prove nothing. `ingest/mock_documents.py` apportions by largest remainder so
    the sums land exactly.
    """
    for d in docs_of("form20"):
        run([py, "-m", "ingest.parse_form20", str(MOCK_DIR / d["path"]),
             "--ac", str(d["ac"]), "--election", d["election"], "--load", "--replace"],
            f"parse_form20 {d['path']}")


def step_crosswalk(py: str) -> None:
    """Bind the non-anchor elections' PS numbers onto the anchored booths."""
    anchors = {d["election"] for d in docs_of("ps_list") if d["anchor"]}
    done: set[tuple[int, str]] = set()
    for d in docs_of("ps_list"):
        key = (d["ac"], d["election"])
        if d["election"] in anchors or key in done:
            continue
        done.add(key)
        run([py, "-m", "ingest.crosswalk", "--ac", str(d["ac"]),
             "--election", d["election"], "--apply"],
            f"crosswalk {d['election']}")


def step_roll(py: str) -> None:
    """The mother roll, then the supplement.

    `--link-election` on the mother roll is what gives the stack any turnout at
    all: `mv_result_booth_wide` reads its denominator from the roll revision an
    election is linked to, and nothing in this repo wrote `election_roll_link`
    until that flag existed (B1).
    """
    for kind in ("roll_mother", "roll_supplement"):
        for d in docs_of(kind):
            cmd = [py, "-m", "ingest.parse_roll", str(MOCK_DIR / d["path"]),
                   "--ac", str(d["ac"]), "--election", d["election"],
                   "--revision", d["revision"], "--date", d["date"], "--load"]
            if d["supplement"]:
                cmd.append("--supplement")
            else:
                cmd += ["--link-election", d["link_election"]]
            run(cmd, f"parse_roll {d['path']}")


