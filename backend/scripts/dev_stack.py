def build_env(url: str) -> dict:
    """The environment the loaders and the API run with.

    `JWT_SECRET` is generated once per `.devstack` and kept, so a token issued
    before a rebuild still verifies and nobody has to sign in twice while
    debugging. It is a development secret in a gitignored directory and is
    never a deployment secret - `common/secrets.py` rejects the placeholder
    values from .env.example, and this is not one of them.
    """
    secret_file = STATE_DIR / "jwt_secret"
    if not secret_file.exists():
        secret_file.write_text(secrets.token_hex(32), encoding="utf-8")
        try:
            secret_file.chmod(0o600)
        except OSError:
            pass
    env = {
        "DATABASE_URL": url,
        "JWT_SECRET": secret_file.read_text(encoding="utf-8").strip(),
        "AUTH_MODE": "password",
        "CHAT_ENABLED": "false",
        "API_CORS_ORIGINS": "http://localhost:5173,http://127.0.0.1:5173",
        "RAW_DIR": str(STATE_DIR / "raw"),
        "OCR_DIR": str(STATE_DIR / "ocr"),
        "BACKUP_DIR": str(STATE_DIR / "backups"),
        "STORAGE_BACKEND": "local",
        "RETAIN_RAW_ROLLS": "true",
        "LOG_LEVEL": "INFO",
        "PYTHONIOENCODING": "utf-8",
        "PYTHONPATH": str(APP_ROOT),
    }
    for key, value in env.items():
        os.environ[key] = value
    for key in ("RAW_DIR", "OCR_DIR", "BACKUP_DIR"):
        Path(env[key]).mkdir(parents=True, exist_ok=True)
    return env


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rebuild", action="store_true",
                    help="drop the database and the generated documents, then build again")
    ap.add_argument("--no-serve", action="store_true", help="build and exit")
    ap.add_argument("--url", action="store_true", help="print DATABASE_URL and exit")
    ap.add_argument("--test-url", action="store_true",
                    help="create the throwaway database tests/e2e needs, print its "
                         "URL and exit. Set E2E_DATABASE_URL to it.")
    ap.add_argument("--stop", action="store_true", help="stop the embedded PostgreSQL")
    ap.add_argument("--ac", type=int, default=32, help="which AC to load booth data for")
    ap.add_argument("--booths", type=int, default=120)
    ap.add_argument("--roll-booths", type=int, default=12,
                    help="booths the generated roll covers. The rest have no electors "
                         "and so no turnout, which is correct and worth seeing.")
    ap.add_argument("--seed", type=int, default=20241123)
    ap.add_argument("--from-step", choices=STEPS,
                    help="re-run from this step onwards, keeping the database")
    ap.add_argument("--synthetic", action="store_true",
                    help="build the mock dataset (generated PDFs, roll, community "
                         "estimates, map points) instead of the real Form 20")
    args = ap.parse_args(argv)

    if args.stop:
        return stop_postgres()

    # Serving keeps this process alive, so the cluster can die with it. Building
    # only must leave it running, or the stack is unusable the moment we exit.
    cleanup = "stop" if not args.no_serve else None
    server, base_uri = start_postgres(cleanup)
    url = ensure_database(base_uri, drop=args.rebuild)
    build_env(url)

    if args.url:
        print(url)
        return 0

    if args.test_url:
        # tests/e2e drops and rebuilds the schema, and its fixture refuses any
        # URL whose database name does not contain 'test'. Creating it here is
        # what makes the instructions in RUN.md work without a psql prompt.
        print(ensure_test_database(base_uri))
        return 0

    steps = STEPS_SYNTHETIC if args.synthetic else STEPS_REAL
    mode = "synthetic" if args.synthetic else "real"
    state = read_state()
    if state.get("mode", "synthetic" if state.get("done") else mode) != mode and not args.rebuild:
        fail(f"this database was built in {state.get('mode', 'synthetic')} mode; "
             f"add --rebuild to rebuild it in {mode} mode")
    if args.rebuild:
        state = {"done": [], "version": 1}
        if MOCK_DIR.exists():
            for path in MOCK_DIR.glob("*"):
                path.unlink()
    state["mode"] = mode
    if args.from_step:
        if args.from_step not in steps:
            fail(f"{args.from_step} is not a step in {mode} mode: {', '.join(steps)}")
        cut = steps.index(args.from_step)
        state["done"] = [s for s in state["done"] if s in steps and steps.index(s) < cut]

    python = sys.executable
    started = time.monotonic()
    for step in steps:
        if step in state["done"]:
            log(f"skip {step} (already done; --rebuild or --from-step {step} to redo)")
            continue
        log(f"--- {step} ---")
        STEP_FUNCS[step](python, args)
        state["done"].append(step)
        write_state(state)
    log(f"build complete in {time.monotonic() - started:.1f}s")

    print_report(url, summarise(), mode)

    if args.no_serve:
        log("PostgreSQL is left running. Stop it with: "
            "python scripts/dev_stack.py --stop")
        return 0

    try:
        serve()
    except KeyboardInterrupt:
        log("stopping")
    finally:
        del server
    return 0


if __name__ == "__main__":
    sys.exit(main())
