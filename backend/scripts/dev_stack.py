"""The whole stack on a laptop, in one command. No Docker, no admin rights.

    python scripts/dev_stack.py

It starts an embedded PostgreSQL, applies every migration, loads the seed,
loads the **real Giridih Form 20** for VS-2024 and VS-2019 (db/seed/form20/,
through ingest/load_form20_tables.py), refreshes the materialized views,
creates one user per role, prints the credentials, and serves the API on
http://localhost:8000.

    python scripts/dev_stack.py --synthetic    # the mock dataset instead (see below)
    python scripts/dev_stack.py --rebuild      # throw the database away first
    python scripts/dev_stack.py --no-serve     # build, then exit
    python scripts/dev_stack.py --url          # print DATABASE_URL and exit
    python scripts/dev_stack.py --stop         # stop the embedded server

Why this exists. Every gate in this project that needed a database was recorded
as NOT VERIFIED HERE, because the build environment has no Docker, no
PostgreSQL service and no administrator rights (DECISIONS.md D-002). The
`pgserver` wheel ships a self-contained PostgreSQL 16 that runs as an ordinary
user out of a directory, which removes that excuse entirely: migrations apply,
views refresh, the loaders run, and the API answers from real rows.

The wheel's PostgreSQL is minimal - plpgsql and pgvector, no PostGIS, no
pg_trgm, no unaccent - which is what finding N4 and the header of
0001_extensions.sql are about. The schema detects what it has and declares its
two geometry columns accordingly, so this stack is the same schema as the
deployment, not a reduced one.

**The data.** By default Giridih's booth results are the real ECI Form 20:
367 polling stations, every candidate, postal ballots. The Form 20 has no
polling-station names, electors or locations, so booths are placeholders
("PS list not loaded"), booth turnout and new-voter figures are absent, and
the map has outlines but no points - each says what it needs.

With `--synthetic`, booth-level numbers are generated by
`ingest/mock_documents.py` (registered as synthetic in source_doc) and are not
evidence about any constituency: that build proves the PDF loaders, rolls and
geocoding work, not that any figure is right.

Everything lives under `.devstack/`, which is gitignored:

    .devstack/pgdata/     the embedded PostgreSQL cluster
    .devstack/mock/       the generated source documents and their manifest
    .devstack/state.json  what has been built, so a re-run is fast
    .devstack/users.json  the dev credentials this script printed
"""

