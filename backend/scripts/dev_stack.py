def step_form20_real(py: str, args) -> None:
    """Every real Form 20 in db/seed/form20/ (ingest.load_form20_tables.seed_loads):
    per AC the VS-2024 file first (it creates the booths), then the others onto
    the same booths if their station numbering is stable. Then the 2024
    polling-station list names and places AC-32's booths, and the modelled
    layers (roll, community) are fitted to what was loaded."""
    run([py, "-m", "ingest.load_form20_tables", "--all-seed"], "ingest.load_form20_tables --all-seed")
    run([py, "-m", "ingest.load_ps_list"], "ingest.load_ps_list")
    for ac, csv_name in ((32, "demography_ac32.csv"), (31, "demography_ac31.csv")):
        run([py, "-m", "ingest.load_csv", "demography",
             str(APP_ROOT / "db" / "seed" / "census" / csv_name), "--ac", str(ac)],
            f"ingest.load_csv demography AC {ac}")
    run([py, "-m", "ingest.load_csv", "candidate_profile",
         str(APP_ROOT / "db" / "seed" / "candidates" / "candidate_profiles_ac32.csv"), "--ac", "32"],
        "ingest.load_csv candidate_profile")
    run([py, "-m", "ingest.modelled_overlay", "--ac", "32"], "ingest.modelled_overlay")


def step_refresh(py: str) -> None:
    # --blocking: REFRESH ... CONCURRENTLY cannot run on a view that has never
    # been populated, which is every view in a freshly built stack. refresh.py
    # falls back on its own, but doing fourteen failed attempts first turns a
    # clean build into a wall of warnings.
    run([py, "-m", "analytics.refresh", "--blocking"], "analytics.refresh")


def step_users(py: str) -> None:
    """Bootstrap login users: single APP_USERNAME when set, else one user per role."""
    if (os.environ.get("APP_USERNAME") or "").strip():
        run([py, "-m", "scripts.ensure_single_user"], "ensure_single_user")
        return
    import psycopg

    blocks: list[dict] = []
    with psycopg.connect(os.environ["DATABASE_URL"], row_factory=psycopg.rows.dict_row) as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT b.block_id, b.name_en, a.ac_number, COUNT(bo.booth_uid) AS booths "
                "FROM block b JOIN ac a ON a.ac_id = b.ac_id "
                "LEFT JOIN area ar ON ar.block_id = b.block_id "
                "LEFT JOIN booth bo ON bo.area_id = ar.area_id "
                "GROUP BY b.block_id, b.name_en, a.ac_number "
                "HAVING COUNT(bo.booth_uid) > 0 ORDER BY b.block_id")
            blocks = [dict(r) for r in cur.fetchall()]
    if not blocks:
        fail("no block has any booth, so a block-role user would see nothing. "
             "The PS list step did not load.")

    created = []
    for spec in DEV_USERS:
        cmd = [py, "-m", "scripts.create_admin", "--phone", spec["phone"],
               "--name", spec["name"], "--role", spec["role"], "--generate-password"]
        block = None
        if spec["block"] == "second":
            block = blocks[1] if len(blocks) > 1 else blocks[0]
            cmd += ["--block", str(block["block_id"])]
        # --generate-password, and never a password piped to stdin. `getpass` on
        # Windows reads the console device directly through msvcrt and ignores
        # the process's own stdin, so feeding it a password over a pipe does not
        # fail - it blocks for ever on a prompt nobody can see.
        proc = subprocess.run(
            cmd, cwd=APP_ROOT, env=dict(os.environ), stdin=subprocess.DEVNULL,
            capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
        if proc.returncode != 0:
            sys.stderr.write(proc.stdout or "")
            sys.stderr.write(proc.stderr or "")
            fail(f"could not create the {spec['role']} user")
        password = _printed_password(proc.stdout, spec["phone"])
        created.append({
            "phone": spec["phone"], "name": spec["name"], "role": spec["role"],
            "password": password,
            "block_id": block["block_id"] if block else None,
            "block_name": block["name_en"] if block else None,
            "booths_visible": block["booths"] if block else None,
        })
    USERS_FILE.write_text(json.dumps(created, indent=2), encoding="utf-8")
    # 0600 on POSIX. On Windows the file inherits the user profile's ACL, which
    # is already private; chmod is a no-op there and is not pretended otherwise.
    try:
        USERS_FILE.chmod(0o600)
    except OSError:
        pass


