def summarise() -> dict:
    """What actually landed in the database. Printed, and worth reading.

    A build that "succeeded" while loading nothing is the failure mode this
    guards: every count below comes from the database, not from the generator.
    """
    import psycopg

    counts: dict[str, object] = {}
    with psycopg.connect(os.environ["DATABASE_URL"], row_factory=psycopg.rows.dict_row) as conn:
        with conn.cursor() as cur:
            for table in ("ac", "block", "area", "booth", "ps_list_entry",
                          "booth_crosswalk", "candidate", "result_booth",
                          "result_booth_meta", "roll_revision", "roll_snapshot",
                          "roll_change", "caste_estimate", "election_roll_link",
                          "review_queue"):
                cur.execute(f"SELECT COUNT(*) AS n FROM {table}")
                counts[table] = cur.fetchone()["n"]
            cur.execute(
                "SELECT election_label, COUNT(*) AS booths, "
                "       COUNT(turnout_pct) AS with_turnout, "
                "       COUNT(margin_pct) AS with_margin, "
                "       SUM(valid_votes) AS valid_votes "
                "FROM mv_result_booth_wide GROUP BY election_label ORDER BY election_label")
            counts["by_election"] = [dict(r) for r in cur.fetchall()]
            # mv_ac_summary is keyed on ac_id and election_id, not on ac_number:
            # it is one row per contest per AC, so the AC's own columns come
            # from `ac` and the baseline contest is the one to report.
            cur.execute(
                "SELECT a.ac_number, a.name_en, a.verified, s.election_label, "
                "       s.booths, s.electors, s.winner_party, s.margin_pct, s.turnout_pct "
                "FROM ac a "
                "LEFT JOIN mv_ac_summary s ON s.ac_id = a.ac_id AND s.is_baseline "
                "ORDER BY a.ac_number")
            counts["acs"] = [dict(r) for r in cur.fetchall()]
    return counts


