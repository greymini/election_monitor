def start_postgres(cleanup: str | None) -> tuple[object, str]:
    """Start (or attach to) the embedded cluster and return (server, base URI).

    `cleanup_mode=None` leaves the cluster running when this process exits,
    which is what `--no-serve` needs: the point of building the stack is to use
    it afterwards from pytest, psql or the Vite dev server. `--stop` shuts it
    down.
    """
    try:
        import pgserver
    except ModuleNotFoundError:
        fail("pgserver is not installed. It is in requirements-dev.txt:\n"
             "    .venv/Scripts/python -m pip install -r requirements-dev.txt")

    STATE_DIR.mkdir(parents=True, exist_ok=True)
    log(f"starting the embedded PostgreSQL in {PGDATA}")
    server = pgserver.get_server(PGDATA, cleanup_mode=cleanup)
    uri = server.get_uri()
    log(f"PostgreSQL is up: {uri}")
    return server, uri


def stop_postgres() -> int:
    if not (PGDATA / "PG_VERSION").exists():
        log("no cluster in .devstack/pgdata; nothing to stop")
        return 0
    import pgserver

    server = pgserver.get_server(PGDATA, cleanup_mode="stop")
    server.cleanup()
    log("stopped")
    return 0


def database_url(base_uri: str, name: str = DEV_DB) -> str:
    """`base_uri` with its database name replaced by `name`.

    Only the URL *path* is the database. On Windows pgserver hands out a TCP URI
    (`postgresql://postgres:@localhost:5432/postgres`), but on macOS and Linux it
    uses a Unix socket and puts the socket directory in the query string
    (`postgresql://postgres:@/postgres?host=/abs/path/pgdata`). Splitting the
    whole string on its last "/" therefore cut into the socket path there.
    """
    from urllib.parse import urlsplit, urlunsplit

    parts = urlsplit(base_uri)
    return urlunsplit(parts._replace(path="/" + name))


def ensure_test_database(base_uri: str) -> str:
    """The throwaway database `tests/e2e` rebuilds from scratch on every run."""
    import psycopg

    with psycopg.connect(base_uri, autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (TEST_DB,))
        if cur.fetchone() is None:
            log(f"creating {TEST_DB}")
            cur.execute(f'CREATE DATABASE "{TEST_DB}"')
    return database_url(base_uri, TEST_DB)


def ensure_database(base_uri: str, drop: bool) -> str:
    import psycopg

    url = database_url(base_uri)
    with psycopg.connect(base_uri, autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (DEV_DB,))
        exists = cur.fetchone() is not None
        if exists and drop:
            log(f"dropping {DEV_DB}")
            cur.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                        "WHERE datname = %s AND pid <> pg_backend_pid()", (DEV_DB,))
            cur.execute(f'DROP DATABASE "{DEV_DB}"')
            exists = False
        if not exists:
            log(f"creating {DEV_DB}")
            cur.execute(f'CREATE DATABASE "{DEV_DB}"')
    return url


