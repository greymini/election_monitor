"""Generate synthetic source documents for local development.

    python -m ingest.mock_documents --ac 32 --out-dir raw/mock

What it writes, for one constituency:

  * a **polling-station list** per block, per election, as a ruled-table PDF;
  * a **Form 20** per election, as a ruled-table PDF, whose per-column sums
    equal the published AC totals in `result_ac_total` exactly;
  * a **mother electoral roll** and one **supplement**, as flowed-text PDFs,
    covering the first few booths at a realistic elector density;
  * `manifest.json`, which `scripts/dev_stack.py` reads to know what to load and
    in which order.

Why generate documents rather than insert rows. Everything this product shows is
derived, and the derivation starts at a PDF: column resolution (3.1), the
booth-sum-versus-published-total gate (LLD 4.2), the crosswalk, the roll
aggregation. A fixture that inserts into `result_booth` skips all of it, which is
how C1 - every candidate loaded with a NULL party, every booth reporting a 100%
margin - survived a green test suite, and how `parse_pslist`, `parse_roll` and
`parse_form20` each came to contain inserts that the NOT NULL constraints added
in 0014 reject outright. Going in through the front door is the only way the
loaders get exercised.

**These documents are synthetic and say so on every page.** Every figure except
the published AC totals is invented by the deterministic generator below. Nothing
here is evidence about Giridih, and `--seed` fixes the output so two developers
building the stack see the same numbers.

Deliberate limitations, all of which `UAT_READINESS.md` records:

  * **Latin script only.** `common/pdf_writer.py` has the base-14 fonts and no
    Devanagari, so the Devanagari branches of `ingest/resolve.py` and
    `ingest/parse_roll.py` are not exercised by this generator. They are covered
    by the unit tests, which pass Devanagari strings directly.
  * **Ruled tables with a clean text layer.** No OCR path, no skew, no merged
    cells. A real CEO PDF is worse than this in ways no generator will guess.
  * **The roll covers a few booths, not the whole electorate.** Giridih's
    published electorate is 304,898, and a roll PDF that enumerates every one of
    them is about 4,500 pages. The booths outside the roll have NULL electors
    and therefore no turnout, which is the correct behaviour (B4) and worth
    seeing on the page.
"""

