# ---------------------------------------------------------------------------
# Deterministic pseudo-randomness
#
# `random.Random` would do, but its stream is an implementation detail of the
# standard library; a CPython upgrade that reshuffles it would silently change
# every number in a dev stack and in any test that asserts on one. A named hash
# is reproducible across versions and machines, which is the only property this
# needs.
# ---------------------------------------------------------------------------

def _hash(*parts: object) -> int:
    import hashlib

    key = "|".join(str(p) for p in parts).encode("utf-8")
    return int.from_bytes(hashlib.sha256(key).digest()[:8], "big")


def unit(*parts: object) -> float:
    """A stable float in [0, 1) from the given parts."""
    return _hash(*parts) / 2**64


def pick(items: list, *parts: object):
    return items[_hash(*parts) % len(items)]


def apportion(total: int, weights: list[float]) -> list[int]:
    """Split `total` across `weights` so the parts sum to exactly `total`.

    Largest-remainder, because the Form 20 gate compares the booth sum with the
    published AC total at tolerance zero (LLD 4.2). Rounding each share
    independently would miss by a few votes and the generator would produce
    documents that its own loader refuses - which is a fine test of the gate and
    a useless way to build a dev stack.
    """
    if total == 0 or not weights:
        return [0] * len(weights)
    positive = [max(w, 0.0) for w in weights]
    mass = sum(positive)
    if mass <= 0:
        positive = [1.0] * len(weights)
        mass = float(len(weights))
    exact = [total * w / mass for w in positive]
    floors = [int(math.floor(x)) for x in exact]
    shortfall = total - sum(floors)
    order = sorted(range(len(weights)), key=lambda i: (-(exact[i] - floors[i]), i))
    for k in range(shortfall):
        floors[order[k % len(order)]] += 1
    return floors


