@dataclass
class Station:
    ps_number: int
    block_id: int
    block_name: str
    area: str
    building: str
    village: str
    roll_part: int


@dataclass
class Contestant:
    """One Form 20 column."""

    header: str              # exactly what the header cell prints
    published_votes: int | None
    is_seeded: bool


@dataclass
class ElectionPlan:
    label: str
    contestants: list[Contestant]
    published_nota: int | None
    stations: list[Station]
    # ps_number -> per-column votes, nota, rejected
    rows: dict[int, dict] = field(default_factory=dict)


def build_stations(ac_number: int, blocks: list[dict], wards: list[str],
                   count: int, seed: int) -> list[Station]:
    """`count` polling stations spread over this AC's blocks.

    Stations in an urban block are filed under a seeded ward name, which
    `parse_pslist.resolve_area` matches through `area_alias`. Rural stations get
    an invented panchayat name, which it creates - which is the behaviour
    db/seed/README.md asks for, since inventing panchayat names in the seed
    would silently corrupt every rollup.
    """
    if not blocks:
        raise ValueError("this AC has no blocks seeded; add them to db/seed/ac_blocks.csv")

    stations: list[Station] = []
    # Proportional split, so a three-block AC does not put everything in one.
    shares = apportion(count, [1.0] * len(blocks))
    ps = 1
    for block, n in zip(blocks, shares, strict=True):
        urban = block["kind"] == "ulb"
        for k in range(n):
            if urban and wards:
                area = wards[k % len(wards)]
                village = area
            else:
                stem = pick(PLACE_STEMS, seed, ac_number, block["block_id"], k // 4)
                area = f"{stem} Panchayat"
                village = stem if k % 3 == 0 else f"{stem} {'ABCDEFGH'[k % 8]}"
            stations.append(Station(
                ps_number=ps,
                block_id=block["block_id"],
                block_name=block["name_en"],
                area=area,
                building=f"{pick(BUILDING_KINDS, seed, ac_number, ps)} {village}",
                village=village,
                roll_part=ps,
            ))
            ps += 1
    return stations


def churn_stations(stations: list[Station], label: str, seed: int,
                   renamed: int, replaced: int) -> list[Station]:
    """An older election's list: same places, renumbered, a few changed.

    Without this every list is identical, every crosswalk match is exact, and
    the review queue, the fuzzy band and `booth_lineage` are all empty - so the
    Admin review queue has nothing to act on and B2 (a station scoring between
    0.65 and 0.85 being dropped instead of queued) cannot be seen at all.

    Three kinds of change, matching what actually happens between revisions:

      * **renumbered.** PS numbers are reversed within each block. This is the
        crosswalk's entire reason for existing (B3), and it means the match has
        to come from the name, not the number.
      * **renamed.** The building kind changes but the village does not, so the
        score lands in the fuzzy band and the row is loaded with reviewed=false.
      * **replaced.** Both building and village are new, so nothing matches and
        the crosswalk mints a booth with method 'new'.
    """
    by_block: dict[int, list[Station]] = {}
    for s in stations:
        by_block.setdefault(s.block_id, []).append(s)

    out: list[Station] = []
    for block_id, group in by_block.items():
        numbers = [s.ps_number for s in group]
        for s, number in zip(group, reversed(numbers), strict=True):
            out.append(Station(**{**asdict(s), "ps_number": number, "roll_part": number}))
        del block_id

    out.sort(key=lambda s: s.ps_number)
    touched = sorted(
        range(len(out)),
        key=lambda i: unit(seed, label, "churn", out[i].ps_number),
    )[: renamed + replaced]

    for rank, index in enumerate(touched):
        s = out[index]
        if rank < renamed:
            kinds = [k for k in BUILDING_KINDS if not s.building.startswith(k)]
            s.building = f"{pick(kinds, seed, label, s.ps_number, 'rename')} {s.village}"
        else:
            stem = pick(PLACE_STEMS, seed, label, s.ps_number, "replace")
            s.village = f"{stem} Extension"
            s.building = f"{pick(BUILDING_KINDS, seed, label, s.ps_number, 'nb')} {s.village}"
    return out


def plan_election(label: str, contestants: list[Contestant], published_nota: int | None,
                  stations: list[Station], seed: int, ac_number: int) -> ElectionPlan:
    """Decide every number this election's Form 20 will print.

    Per column, the published AC total is apportioned across booths with a
    smooth spatial profile unique to that column, so the diverging map ramp and
    the margin distribution have structure rather than noise. The apportionment
    is exact, so each column sums to its published total and the LLD 4.2 gate
    passes for the right reason.
    """
    plan = ElectionPlan(label=label, contestants=contestants,
                        published_nota=published_nota, stations=stations)
    n = len(stations)
    if n == 0:
        return plan

    columns: list[list[int]] = []
    for c in contestants:
        phase = 2 * math.pi * unit(seed, ac_number, label, c.header, "phase")
        weights = [
            1.0 + 0.45 * math.sin(2 * math.pi * i / max(n, 1) + phase)
                + 0.20 * math.sin(6 * math.pi * i / max(n, 1) + phase * 1.7)
                + 0.10 * unit(seed, label, c.header, i)
            for i in range(n)
        ]
        if c.published_votes is not None:
            total = c.published_votes
        else:
            # An unseeded column (an independent) has no published total, so one
            # is invented: a small, deterministic share of the largest seeded
            # column. Flagged as not cross-checked by ac_totals_by_column.
            biggest = max((x.published_votes or 0) for x in contestants) or 1000 * n
            total = int(biggest * (0.01 + 0.03 * unit(seed, label, c.header, "share")))
        columns.append(apportion(total, weights))

    nota_weights = [1.0 + 0.3 * unit(seed, label, "nota", i) for i in range(n)]
    nota = apportion(published_nota, nota_weights) if published_nota else [0] * n

    for i, station in enumerate(stations):
        votes = [col[i] for col in columns]
        nota_i = nota[i]
        valid = sum(votes) + nota_i
        # Rejected votes are a tiny fraction, and zero at some booths, because
        # metric_votes_polled adds them to the valid total and a column that is
        # never zero would hide a NULL-versus-zero mistake.
        rejected = 0 if i % 7 == 0 else int(valid * (0.0005 + 0.0025 * unit(seed, label, "rej", i)))
        plan.rows[station.ps_number] = {
            "votes": votes,
            "nota": nota_i,
            "rejected": rejected,
            "total_valid": valid,
            "total": valid + rejected,
            "tendered": 1 if i % 23 == 0 else 0,
        }
    return plan


