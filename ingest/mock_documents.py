def generate(ac_number: int, out_dir: Path, booths: int, roll_booths: int,
             elections: list[str], independents: int, seed: int,
             turnout_low: float, turnout_high: float,
             renamed: int = 4, replaced: int = 2) -> dict:
    from common.db import cursor

    out_dir.mkdir(parents=True, exist_ok=True)
    documents: list[dict] = []

    with cursor() as cur:
        ac = read_ac(cur, ac_number)
        anchor_stations = build_stations(ac_number, ac["blocks"], ac["wards"], booths, seed)

        # The newest election's list is the anchor: it is what mints booth_uids.
        # Older lists are renumbered and partly changed by churn_stations, then
        # bound to those booths by ingest/crosswalk.py, which is the only safe
        # way to re-number (B5).
        anchor_label = elections[0]
        plans: dict[str, ElectionPlan] = {}
        for label in elections:
            found = read_contestants(cur, ac["ac_id"], label, independents)
            if found is None:
                log.warning("%s has no published candidate totals for AC %s - skipping. "
                            "Add them to db/seed/ac_totals.csv to include it.",
                            label, ac_number)
                continue
            contestants, nota = found
            stations = (anchor_stations if label == anchor_label
                        else churn_stations(anchor_stations, label, seed, renamed, replaced))
            plans[label] = plan_election(label, contestants, nota, stations, seed, ac_number)
            log.info("%s: %d station(s), %d column(s), %s", label, len(stations),
                     len(contestants),
                     ", ".join(f"{c.header}={c.published_votes}" for c in contestants))

    if not plans:
        raise ValueError(
            f"AC {ac_number} has no election with published candidate totals, so no "
            f"Form 20 can be generated. db/seed/ac_totals.csv is where they go."
        )
    if anchor_label not in plans:
        raise ValueError(
            f"{anchor_label} must have published candidate totals: it is the first "
            f"election given and therefore the anchor whose PS list mints the booths."
        )

    # -- PS lists, one per block per election ------------------------------
    for label, plan in plans.items():
        for block in ac["blocks"]:
            subset = [s for s in plan.stations if s.block_id == block["block_id"]]
            if not subset:
                continue
            slug = block["name_en"].lower().replace(" ", "-")
            path = out_dir / f"ps_list_{ac_number}_{label}_{slug}.pdf"
            path.write_bytes(render_ps_list(ac_number, ac["name_en"], label,
                                            block["name_en"], subset))
            documents.append({
                "kind": "ps_list", "path": path.name, "election": label,
                "ac": ac_number, "block_id": block["block_id"],
                "block_name": block["name_en"], "stations": len(subset),
                "anchor": label == anchor_label,
            })

    # -- Form 20 per election ----------------------------------------------
    for label, plan in plans.items():
        path = out_dir / f"form20_{ac_number}_{label}.pdf"
        path.write_bytes(render_form20(ac_number, ac["name_en"], plan))
        checks = {c.header: c.published_votes for c in plan.contestants if c.is_seeded}
        documents.append({
            "kind": "form20", "path": path.name, "election": label, "ac": ac_number,
            "stations": len(plan.stations), "columns": len(plan.contestants),
            "published_checks": checks, "published_nota": plan.published_nota,
        })

    # -- Roll: mother plus one supplement, over the first few booths -------
    baseline = anchor_label
    covered = plans[baseline].stations[:max(0, roll_booths)]
    electors: dict[int, int] = {}
    for s in covered:
        row = plans[baseline].rows[s.ps_number]
        polled = row["total_valid"] + row["rejected"]
        share = turnout_low + (turnout_high - turnout_low) * unit(seed, "turnout", s.ps_number)
        electors[s.ps_number] = max(polled + 1, int(round(polled / share)))

    if covered:
        mother_label = f"{baseline}-MOTHER"
        path = out_dir / f"roll_mother_{ac_number}.pdf"
        path.write_bytes(render_roll(ac_number, ac["name_en"], mother_label,
                                     covered, electors, seed))
        documents.append({
            "kind": "roll_mother", "path": path.name, "ac": ac_number,
            "election": baseline, "revision": mother_label,
            "date": "2024-01-05", "supplement": False,
            "booths": len(covered), "electors": sum(electors.values()),
            # The baseline election reads its electors through
            # election_roll_link, so dev_stack links this revision to it.
            "link_election": baseline,
        })

        supp_label = f"{baseline}-SUPP-1"
        path = out_dir / f"roll_supplement_{ac_number}.pdf"
        path.write_bytes(render_supplement(ac_number, ac["name_en"], supp_label,
                                           covered, electors, seed))
        documents.append({
            "kind": "roll_supplement", "path": path.name, "ac": ac_number,
            "election": baseline, "revision": supp_label,
            "date": "2024-10-15", "supplement": True, "booths": len(covered),
        })

    manifest = {
        "generator": "ingest/mock_documents.py",
        "synthetic": True,
        "ac": ac_number,
        "ac_name": ac["name_en"],
        "seed": seed,
        "booths": len(anchor_stations),
        "roll_booths": len(covered),
        "elections": list(plans),
        "stations": [asdict(s) for s in anchor_stations],
        "documents": documents,
    }
    (out_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate synthetic Form 20, PS list and roll PDFs for local development",
        epilog="Needs DATABASE_URL and a seeded database: the published AC totals the "
               "Form 20 must reconcile to are read from result_ac_total.",
    )
    ap.add_argument("--ac", type=int, default=32, help="AC number (default 32, Giridih)")
    ap.add_argument("--out-dir", default="raw/mock", help="where to write the PDFs")
    ap.add_argument("--booths", type=int, default=120,
                    help="polling stations in the generated AC (default 120)")
    ap.add_argument("--roll-booths", type=int, default=12,
                    help="how many booths the electoral roll covers (default 12). "
                         "The rest get NULL electors and no turnout, which is correct "
                         "and worth seeing.")
    ap.add_argument("--elections", default="VS-2024,VS-2019,VS-2014",
                    help="comma-separated election labels, baseline first")
    ap.add_argument("--independents", type=int, default=2,
                    help="extra independent columns per Form 20 (default 2)")
    ap.add_argument("--renamed", type=int, default=4,
                    help="stations whose building changes in an older list, so the "
                         "crosswalk scores them in the review band (default 4)")
    ap.add_argument("--replaced", type=int, default=2,
                    help="stations replaced outright in an older list, so the "
                         "crosswalk has to mint a booth (default 2)")
    ap.add_argument("--seed", type=int, default=20241123,
                    help="fixes every generated number")
    ap.add_argument("--turnout-low", type=float, default=0.56)
    ap.add_argument("--turnout-high", type=float, default=0.78)
    args = ap.parse_args(argv)

    try:
        manifest = generate(
            ac_number=args.ac, out_dir=Path(args.out_dir), booths=args.booths,
            roll_booths=args.roll_booths,
            elections=[e.strip() for e in args.elections.split(",") if e.strip()],
            independents=args.independents, seed=args.seed,
            turnout_low=args.turnout_low, turnout_high=args.turnout_high,
            renamed=args.renamed, replaced=args.replaced,
        )
    except ValueError as exc:
        log.error("%s", exc)
        return 2

    log.info("wrote %d document(s) for AC %s-%s into %s",
             len(manifest["documents"]), manifest["ac"], manifest["ac_name"], args.out_dir)
    for d in manifest["documents"]:
        log.info("  %-16s %s", d["kind"], d["path"])
    log.info("manifest: %s", Path(args.out_dir) / "manifest.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
