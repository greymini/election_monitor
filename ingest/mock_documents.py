def read_ac(cur, ac_number: int) -> dict:
    cur.execute("SELECT ac_id, name_en FROM ac WHERE ac_number = %s", (ac_number,))
    row = cur.fetchone()
    if row is None:
        raise ValueError(f"AC {ac_number} is not seeded; run db.seed.load_seed first")
    cur.execute(
        "SELECT block_id, name_en, kind FROM block WHERE ac_id = %s ORDER BY block_id",
        (row["ac_id"],),
    )
    blocks = [dict(b) for b in cur.fetchall()]
    cur.execute(
        "SELECT name_en FROM area WHERE ac_id = %s AND kind = 'ward' ORDER BY area_id",
        (row["ac_id"],),
    )
    wards = [w["name_en"] for w in cur.fetchall()]
    return {"ac_id": row["ac_id"], "name_en": row["name_en"], "blocks": blocks, "wards": wards}


def read_contestants(cur, ac_id: int, label: str,
                     independents: int) -> tuple[list[Contestant], int | None] | None:
    """The Form 20 columns for one election, from the published AC totals.

    Returns None when the election has no published candidate totals: the mock
    Form 20 would then have nothing to reconcile against, and a document with
    invented totals for every column is worse than no document, because it would
    make the LLD 4.2 gate look like it had passed on real figures.

    Headers print the bare candidate name, which is what a real Form 20 carries
    and what makes `resolve.py` step 3 - fuzzy-match the name against the seeded
    candidates - the path that actually runs.
    """
    cur.execute(
        "SELECT c.name_en, p.abbr, t.value AS votes, t.metric "
        "FROM result_ac_total t "
        "JOIN election e ON e.election_id = t.election_id "
        "LEFT JOIN candidate c ON c.candidate_id = t.candidate_id "
        "LEFT JOIN party p ON p.party_id = c.party_id "
        "WHERE e.ac_id = %s AND e.label = %s AND t.metric IN ('votes', 'nota') "
        "ORDER BY t.value DESC",
        (ac_id, label),
    )
    contestants: list[Contestant] = []
    nota: int | None = None
    for row in cur.fetchall():
        if row["metric"] == "nota":
            nota = row["votes"]
        elif row["name_en"]:
            contestants.append(Contestant(header=row["name_en"],
                                          published_votes=row["votes"], is_seeded=True))
    if not contestants:
        return None

    for k in range(independents):
        given = pick(GIVEN_NAMES, label, "ind", k)
        surname = pick(SURNAMES, label, "ind", k, "s")
        contestants.append(Contestant(header=f"{given} {surname} (IND)",
                                      published_votes=None, is_seeded=False))
    return contestants, nota


