PS_LIST_HEADER = ["Serial No. of Polling Station", "Name of Polling Station / Building",
                  "Village or Ward covered", "Part No."]


def render_ps_list(ac_number: int, ac_name: str, label: str, block_name: str,
                   stations: list[Station], rows_per_page: int = 28) -> bytes:
    builder = PdfBuilder()
    for start in range(0, len(stations), rows_per_page):
        chunk = stations[start:start + rows_per_page]
        table = Table(
            rows=[PS_LIST_HEADER] + [
                [str(s.ps_number), f"{s.building}, {s.village}", s.area, str(s.roll_part)]
                for s in chunk
            ],
            widths=[70, 300, 200, 60],
            font_size=8,
        )
        builder.add(Page(
            size=A4_LANDSCAPE,
            titles=[f"LIST OF POLLING STATIONS - {label}",
                    f"Assembly Constituency {ac_number}-{ac_name}, {block_name}",
                    SYNTHETIC_BANNER],
            table=table,
        ))
    return builder.to_bytes()


def render_form20(ac_number: int, ac_name: str, plan: ElectionPlan,
                  rows_per_page: int = 22) -> bytes:
    """A Form 20 in the column order Jharkhand prints.

    The tail columns and their labels matter more than they look: `TAIL_LABELS`
    in parse_form20 decides where the candidate run stops, so "Total of Valid
    Votes" has to come immediately after the last candidate and NOTA has to be
    in the tail, not among the candidates.
    """
    header = (["Serial No. of Polling Station"]
              + [c.header for c in plan.contestants]
              + ["Total of Valid Votes", "No. of Rejected Votes", "NOTA", "Total",
                 "No. of Tendered Votes"])
    n_cand = len(plan.contestants)
    widths = ([52] + [max(58, int(620 / max(n_cand, 1))) for _ in range(n_cand)]
              + [58, 58, 40, 52, 52])

    builder = PdfBuilder()
    for start in range(0, len(plan.stations), rows_per_page):
        chunk = plan.stations[start:start + rows_per_page]
        body = []
        for s in chunk:
            r = plan.rows[s.ps_number]
            body.append([str(s.ps_number)] + [str(v) for v in r["votes"]]
                        + [str(r["total_valid"]), str(r["rejected"]), str(r["nota"]),
                           str(r["total"]), str(r["tendered"])])
        builder.add(Page(
            size=A4_LANDSCAPE,
            titles=[f"FORM 20 - FINAL RESULT SHEET - {plan.label}",
                    f"Assembly Constituency {ac_number}-{ac_name}",
                    SYNTHETIC_BANNER],
            table=Table(rows=[header] + body, widths=widths, font_size=6.5),
        ))
    return builder.to_bytes()


def _elector_line(index: int, seed: int, label: str, ps_number: int) -> str:
    """One roll entry, in the shape `ingest/parse_roll` reads.

    The anchors are load-bearing. `NAME_RE` stops the elector name at a
    two-space gap or at one of a fixed set of following labels, and a PDF text
    layer does not promise to preserve a run of spaces - so every name here is
    followed by `House:`, a label the regex knows, rather than by whitespace.
    `RELATIVE_RE` then removes the "Father Name:" span before the name is read,
    which is what stops a father's surname being counted as an elector's.
    """
    given = pick(GIVEN_NAMES, seed, label, ps_number, index, "given")
    surname = pick(SURNAMES, seed, label, ps_number, index // 3, "surname")
    relative = pick(GIVEN_NAMES, seed, label, ps_number, index, "rel")
    epic = f"{EPIC_PREFIX}{(_hash(seed, label, ps_number, index) % 9_000_000) + 1_000_000}"
    # Ages skew the way a real electorate does: more 20-45 than 60+, and a small
    # 18-19 band, so the age-band chart is not flat.
    u = unit(seed, label, ps_number, index, "age")
    age = int(18 + 62 * (u**1.6))
    gender = "Female" if unit(seed, label, ps_number, index, "sex") < 0.48 else "Male"
    if unit(seed, label, ps_number, index, "sex3") > 0.998:
        gender = "Other"
    # Field order matters. RELATIVE_RE strips from "Father Name:" up to the
    # next House/Age/Gender label or end of line, so the relative must be
    # followed by one of those - put it last and the strip would run to the end
    # of the line and swallow the next elector on the same row.
    return (f"{epic} Name: {given} {surname} Father Name: {relative} {surname} "
            f"House: {1 + index % 180} Age: {age} Gender: {gender}")


ENTRIES_PER_LINE = 3
# 64 lines of 5.5pt with 1.35 leading leaves about 50pt of bottom margin on A4
# landscape after four title lines. `test_mock_documents` asserts that the last
# entry of a full page is still read back, so a change here that pushes text off
# the page fails a test rather than silently losing electors.
ROLL_LINES_PER_PAGE = 64
ROLL_FONT = 5.5
ROLL_MARGIN = 14.0


def _elector_row(start: int, count: int, seed: int, label: str, ps_number: int) -> str:
    """Several entries on one line, which is how a roll is actually printed.

    A real roll puts three electors across a row, and `parse_roll` is written
    for exactly that: `scan_mother_roll` counts the EPIC numbers on a line and
    `_attrs_for` pulls that many genders, ages and names from the same line,
    widening forward only when the line is short. One entry per line exercises
    none of it - so a mock that did it would leave the branch the parser exists
    for untested, and that is the branch C7 lived in: gender and age read from a
    different line than the EPIC count.

    Three per line also cuts the page count to a third, which on a document that
    enumerates tens of thousands of electors is the difference between a dev
    stack that builds in half a minute and one that takes three.
    """
    return "   ".join(_elector_line(start + k, seed, label, ps_number)
                      for k in range(count))


def _assert_row_fits(row: str, page_width: float) -> None:
    """A row that overflows gets wrapped, and a wrap mid-entry is a silent fault.

    `PdfBuilder` wraps any body line too wide for the page. For a roll that
    would split one elector's entry across two lines, putting the EPIC on one
    and the gender on the next, and the counts would come out wrong in a way
    that looks like a parser bug. Fail at generation time instead.
    """
    usable = page_width - 2 * ROLL_MARGIN
    width = text_width(row, ROLL_FONT)
    if width > usable:
        raise ValueError(
            f"a roll row is {width:.0f}pt wide and the page allows {usable:.0f}pt, so it "
            f"would wrap and split an elector entry across two lines. Shorten the entry "
            f"shape in _elector_line, lower ROLL_FONT, or reduce ENTRIES_PER_LINE."
        )


def render_roll(ac_number: int, ac_name: str, revision_label: str,
                stations: list[Station], electors: dict[int, int],
                seed: int, lines_per_page: int = ROLL_LINES_PER_PAGE) -> bytes:
    per_page = lines_per_page * ENTRIES_PER_LINE
    builder = PdfBuilder()
    for s in stations:
        total = electors.get(s.ps_number, 0)
        if total <= 0:
            continue
        written = 0
        page_index = 0
        while written < total:
            batch = min(per_page, total - written)
            body = [
                _elector_row(written + offset, min(ENTRIES_PER_LINE, batch - offset),
                             seed, revision_label, s.ps_number)
                for offset in range(0, batch, ENTRIES_PER_LINE)
            ]
            for row in body:
                _assert_row_fits(row, A4_LANDSCAPE[0])
            builder.add(Page(
                size=A4_LANDSCAPE,
                body_size=ROLL_FONT,
                margin=ROLL_MARGIN,
                titles=[f"ELECTORAL ROLL {revision_label} - {ac_number}-{ac_name}",
                        f"Polling Station No. {s.ps_number}   Part No. {s.roll_part}",
                        f"{s.building}, {s.village}   Page {page_index + 1}",
                        SYNTHETIC_BANNER],
                title_size=7.0,
                body=body,
            ))
            written += batch
            page_index += 1
    if not builder.pages:
        raise ValueError("the roll would have no pages: no booth was given an elector count")
    return builder.to_bytes()


def render_supplement(ac_number: int, ac_name: str, revision_label: str,
                      stations: list[Station], electors: dict[int, int],
                      seed: int) -> bytes:
    """A supplement: additions, deletions and modifications under headings.

    One page per station, with all three section headings present. C8 is why
    every station gets its own page with its own headings: the section state
    used to reset per PS group, so every group after the first recorded zero
    additions - a defect only a multi-station document can show.

    One entry per line here, unlike the mother roll. `_deletion_reason` reads a
    reason per *line* and applies it to every entry on it, which is audit
    finding C9 and still open; printing three deletions to a line would bake
    that behaviour into the fixture and make the per-reason counts meaningless.
    A supplement is a few dozen entries per station, so the page count this
    costs does not matter.
    """
    builder = PdfBuilder()
    for s in stations:
        base = electors.get(s.ps_number, 0)
        if base <= 0:
            continue
        n_add = max(2, int(base * (0.010 + 0.020 * unit(seed, "add", s.ps_number))))
        n_del = max(1, int(base * (0.004 + 0.008 * unit(seed, "del", s.ps_number))))
        n_mod = max(1, int(base * (0.002 + 0.004 * unit(seed, "mod", s.ps_number))))

        body: list[str] = ["ADDITIONS"]
        body += [_elector_line(k, seed, f"{revision_label}-add", s.ps_number)
                 for k in range(n_add)]
        body.append("DELETIONS")
        for k in range(n_del):
            reason = ("DEAD" if k % 3 == 0 else "SHIFTED" if k % 3 == 1 else "REPEATED")
            body.append(_elector_line(k, seed, f"{revision_label}-del", s.ps_number)
                        + f" Reason: {reason}")
        body.append("MODIFICATIONS")
        body += [_elector_line(k, seed, f"{revision_label}-mod", s.ps_number)
                 for k in range(n_mod)]

        # Chunked so a station with many additions does not overflow one page.
        for start in range(0, len(body), 64):
            builder.add(Page(
                size=A4_PORTRAIT,
                body_size=7.0,
                titles=[f"SUPPLEMENT {revision_label} - {ac_number}-{ac_name}",
                        f"Polling Station No. {s.ps_number}   Part No. {s.roll_part}",
                        SYNTHETIC_BANNER],
                body=body[start:start + 64],
            ))
    if not builder.pages:
        raise ValueError("the supplement would have no pages")
    return builder.to_bytes()


