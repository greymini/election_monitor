"""Before going live (and after any change to the host): is this deployment safe to run?

    python -m scripts.preflight

Checks, each ok / warn / fail:
  secrets     every secret set, not a placeholder, long enough, and not reused for two purposes
  migrations  every file in db/migrations applied, none edited after it was applied
  media       MEDIA_DIR outside the repo, present, writable and not readable by other users
  worker      a worker has finished a run in the last 5 minutes
  webhook     whether Telegram has a webhook set, and whether that matches BOT_MODE / WEBHOOK_URL
  asr         the speech-to-text engine exists; fake is for tests only; ffmpeg for 16 kHz conversion

Exit code 1 if anything failed. Prints variable names and reasons, never secret values.
"""
from __future__ import annotations

import os
import stat
import sys
import tempfile
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Callable, Mapping

from pulse import migrate
from pulse.common.clock import utcnow
from pulse.config import REPO_ROOT, ConfigError, Settings, load_settings

WORKER_STALE = timedelta(minutes=5)
MIN_DISTINCT_CHARS = 12


@dataclass(frozen=True)
class Check:
    name: str
    status: str          # ok | warn | fail
    detail: str


def check_secrets(env: Mapping[str, str] | None) -> tuple[Check, Settings | None]:
    try:
        s = load_settings(env)
    except ConfigError as e:
        return Check("secrets", "fail", str(e).replace("Refusing to start:", "").strip()), None
    if s.jwt_secret == s.telegram_webhook_secret:
        return Check("secrets", "fail", "JWT_SECRET and TELEGRAM_WEBHOOK_SECRET must differ"), s
    weak = [name for name, value in (("JWT_SECRET", s.jwt_secret), ("TELEGRAM_WEBHOOK_SECRET", s.telegram_webhook_secret))
            if len(set(value)) < MIN_DISTINCT_CHARS]
    if weak:
        return Check("secrets", "fail", f"{', '.join(weak)} look generated by hand (too few distinct characters); "
                                        "use secrets.token_urlsafe(32)"), s
    return Check("secrets", "ok", "all set"), s


def check_migrations(conn, directory: Path = migrate.MIGRATIONS_DIR) -> Check:
    st = migrate.status(conn, directory)
    if st["changed"]:
        return Check("migrations", "fail", f"edited after being applied: {', '.join(st['changed'])}")
    if st["pending"]:
        return Check("migrations", "fail", f"not applied: {', '.join(st['pending'])} (run python -m pulse.migrate)")
    if st["unknown"]:
        return Check("migrations", "warn", f"applied but missing from this checkout: {', '.join(st['unknown'])}")
    return Check("migrations", "ok", "current")


def _inside(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def check_media_dir(path: Path, repo_root: Path = REPO_ROOT, *, posix: bool | None = None) -> Check:
    posix = os.name != "nt" if posix is None else posix
    if _inside(path, repo_root):
        return Check("media", "fail", "MEDIA_DIR is inside the repository; move it out (photos must never be committed)")
    if not path.is_dir():
        return Check("media", "fail", "MEDIA_DIR does not exist")
    try:
        with tempfile.NamedTemporaryFile(dir=path, prefix=".preflight-"):
            pass
    except OSError:
        return Check("media", "fail", "MEDIA_DIR is not writable by this user")
    if posix:
        mode = stat.S_IMODE(path.stat().st_mode)
        if mode & (stat.S_IROTH | stat.S_IWOTH | stat.S_IXOTH):
            return Check("media", "fail", f"MEDIA_DIR is accessible to other users (mode {mode:o}); chmod 700")
        return Check("media", "ok", f"outside the repo, mode {mode:o}")
    return Check("media", "warn", "outside the repo; on Windows check access with icacls (only the service account "
                                  "and administrators)")


def check_asr(engine_name: str) -> Check:
    from pulse import asr
    from pulse.asr.base import converter_available

    try:
        engine = asr.get_engine(engine_name)
    except ValueError as e:
        return Check("asr", "fail", str(e))
    if engine is None:
        return Check("asr", "ok", "ASR_ENGINE=none: voice notes stay audio-only")
    if engine_name == "fake":
        return Check("asr", "warn", "ASR_ENGINE=fake is a test engine; it invents transcripts")
    if not converter_available():
        return Check("asr", "warn", f"engine {engine_name}; ffmpeg not on PATH, so audio is passed unconverted")
    return Check("asr", "ok", f"engine {engine_name}, ffmpeg available")


def check_worker(conn, now: datetime) -> Check:
    last = conn.execute("SELECT max(finished_at) AS t FROM field.job_run").fetchone()["t"]
    if last is None:
        return Check("worker", "fail", "no worker run recorded; start python -m scripts.run_worker")
    age = now - last
    if age > WORKER_STALE:
        return Check("worker", "fail", f"last worker run {int(age.total_seconds() // 60)} minutes ago")
    return Check("worker", "ok", f"last run {int(age.total_seconds())} s ago")


def check_webhook(client, settings: Settings) -> Check:
    try:
        info = client.get_webhook_info()
    except Exception as e:                                       # noqa: BLE001 - reported, not raised
        return Check("webhook", "fail", f"getWebhookInfo failed: {type(e).__name__}")
    url = info.get("url") or ""
    pending = info.get("pending_update_count", 0)
    if settings.bot_mode == "polling":
        if url:
            return Check("webhook", "fail", "BOT_MODE is polling but Telegram has a webhook set; polling cannot run "
                                            "(python -m scripts.webhook delete)")
        return Check("webhook", "ok", "no webhook set; polling mode")
    if not url:
        return Check("webhook", "fail", "BOT_MODE is webhook but no webhook is set (python -m scripts.webhook set)")
    if url != settings.webhook_url:
        return Check("webhook", "fail", "the webhook Telegram has does not match WEBHOOK_URL")
    if info.get("last_error_message"):
        return Check("webhook", "warn", f"set and matching; Telegram reports a recent delivery error, "
                                        f"{pending} updates waiting")
    return Check("webhook", "ok", f"set and matching, {pending} updates waiting")


def run(env: Mapping[str, str] | None = None, *, connect: Callable | None = None, client=None,
        now: datetime | None = None) -> list[Check]:
    """connect(url) → connection and client are injectable for tests."""
    secrets, s = check_secrets(env)
    checks = [secrets]
    if s is None:
        return checks
    checks.append(check_media_dir(s.media_dir))
    checks.append(check_asr(s.asr_engine))
    if connect is None:
        from pulse.db import connect
    try:
        conn = connect(s.database_url)
    except Exception as e:                                       # noqa: BLE001
        checks.append(Check("database", "fail", f"cannot connect: {type(e).__name__}"))
    else:
        with conn:
            checks.append(check_migrations(conn))
            checks.append(check_worker(conn, now or utcnow()))
    if client is None:
        from pulse.bot.client import HttpxTelegramClient
        client = HttpxTelegramClient(s.telegram_bot_token)
    checks.append(check_webhook(client, s))
    return checks


def main() -> int:
    checks = run()
    for c in checks:
        print(f"{c.status.upper():5} {c.name:11} {c.detail}")
    return 1 if any(c.status == "fail" for c in checks) else 0


if __name__ == "__main__":
    sys.exit(main())
